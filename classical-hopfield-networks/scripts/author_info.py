def get_author_info_dict() -> dict:
    """
    Get author information as a dictionary.
    
    Returns:
        Dictionary containing all author information
    """
    return {
        "name": AUTHOR_NAME,
        "affiliation": AUTHOR_AFFILIATION,
        "location": AUTHOR_LOCATION,
        "github": AUTHOR_GITHUB,
        "course": COURSE_NAME,
        "assignment": COURSE_ASSIGNMENT
    }


