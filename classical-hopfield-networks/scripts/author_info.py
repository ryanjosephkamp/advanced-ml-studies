from datetime import datetime
from typing import Optional


# =============================================================================
# AUTHOR INFORMATION CONSTANTS
# =============================================================================

AUTHOR_NAME = "Ryan Kamp"
AUTHOR_AFFILIATION = "Department of Computer Science, University of Cincinnati"
AUTHOR_LOCATION = "Cincinnati, OH, USA"
AUTHOR_GITHUB = "https://github.com/ryanjosephkamp"

COURSE_NAME = "CS7063 Advanced Machine Learning"
COURSE_ASSIGNMENT = "Assignment 2 – Hopfield Networks"


# =============================================================================
# HEADER GENERATION FUNCTIONS
# =============================================================================

def get_script_header(script_name: str, description: str, date: Optional[str] = None) -> str:
    """
    Generate a consistent docstring header for Python scripts.
    
    Args:
        script_name: Name of the script file
        description: Brief description of the script's purpose
        date: Optional date string; if None, uses current date
        
    Returns:
        Formatted docstring header string
    """
    if date is None:
        date = datetime.now().strftime("%B %d, %Y")
    
    header = f'''#!/usr/bin/env python3
"""
{script_name} - {description}

Author: {AUTHOR_NAME}
Affiliation: {AUTHOR_AFFILIATION}
Location: {AUTHOR_LOCATION}
GitHub: {AUTHOR_GITHUB}

Course: {COURSE_NAME}
Assignment: {COURSE_ASSIGNMENT}
Date: {date}
"""'''
    return header


def get_markdown_header(title: str, date: Optional[str] = None) -> str:
    """
    Generate a consistent header for markdown reports.
    
    Args:
        title: Title of the report
        date: Optional date string; if None, uses current date
        
    Returns:
        Formatted markdown header string
    """
    if date is None:
        date = datetime.now().strftime("%B %d, %Y")
    
    header = f"""# {title}

---

**Author:** {AUTHOR_NAME}  
**Affiliation:** {AUTHOR_AFFILIATION}  
**Location:** {AUTHOR_LOCATION}  
**GitHub:** {AUTHOR_GITHUB}

**Course:** {COURSE_NAME}  
**Assignment:** {COURSE_ASSIGNMENT}  
**Date:** {date}

---

"""
    return header


def get_markdown_footer() -> str:
    """
    Generate a consistent footer for markdown reports that are automatically written by scripts.
    
    Returns:
        Formatted markdown footer string
    """
    date = datetime.now().strftime("%B %Y")
    footer = f"""

---

*This report was generated as part of {COURSE_NAME}, {COURSE_ASSIGNMENT}, {date}.*
"""
    return footer


def get_console_header(script_name: str, date: Optional[str] = None) -> str:
    """
    Generate a consistent header for console printouts.
    This header is intended for scripts that produce console output.

    Args:
        script_name: Name of the script file (e.g., "kamp_hw2.py")
        date: Optional date string; if None, uses current date
        
    Returns:
        Formatted console header string
    """
    if date is None:
        date = datetime.now().strftime("%B %d, %Y")
    
    header = f"""
{'=' * 70}
Author: {AUTHOR_NAME}
Affiliation: {AUTHOR_AFFILIATION}
Location: {AUTHOR_LOCATION}
GitHub: {AUTHOR_GITHUB}

Course: {COURSE_NAME}
Assignment: {COURSE_ASSIGNMENT}
Date: {date}

{script_name} Printout
{'=' * 70}
"""
    return header


def print_console_header(script_name: str, date: Optional[str] = None) -> None:
    """
    Print the console header for a script.
    This header is intended for scripts that produce console output.
    
    Args:
        script_name: Name of the script file (e.g., "kamp_hw2.py")
        date: Optional date string; if None, uses current date
    """
    print(get_console_header(script_name, date))


# =============================================================================
