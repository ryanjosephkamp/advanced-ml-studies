# CONSOLE OUTPUT LOGGING (TeeLogger)
# =============================================================================

class TeeLogger:
    """
    Duplicate stdout/stderr to a file while still printing to console.
    Use as a context manager or manually start/stop.
    Usage:
        with TeeLogger('/path/to/log.txt'):
            print("This goes to console AND log file").
    """

    def __init__(self, log_path: str):
        self.log_path = log_path
        self._log_file = None
        self._original_stdout = None
        self._original_stderr = None
        self._tee_stdout = None
        self._tee_stderr = None

    def start(self):
        """Start capturing stdout and stderr to the log file."""
        os.makedirs(os.path.dirname(self.log_path), exist_ok=True)
        self._log_file = open(self.log_path, "w", encoding="utf-8")
        self._original_stdout = sys.stdout
        self._original_stderr = sys.stderr
        self._tee_stdout = _TeeStream(self._original_stdout, self._log_file)
        self._tee_stderr = _TeeStream(self._original_stderr, self._log_file)
        sys.stdout = self._tee_stdout
        sys.stderr = self._tee_stderr

    def stop(self):
        """Stop capturing and restore original stdout/stderr."""
        if self._original_stdout is not None:
            sys.stdout = self._original_stdout
        if self._original_stderr is not None:
            sys.stderr = self._original_stderr
        if self._log_file is not None:
            self._log_file.close()
            self._log_file = None

    def __enter__(self):
        self.start()
        return self

    def __exit__(self, exc_type, exc_val, exc_tb):
        self.stop()
        return False


class _TeeStream:
    """Internal helper that writes to both a console stream and a log file."""

    def __init__(self, console_stream, log_file):
        self.console = console_stream
        self.log_file = log_file

    def write(self, message: str):
        self.console.write(message)
        try:
            self.log_file.write(message)
        except (ValueError, OSError):
            pass  # file may have been closed

    def flush(self):
        self.console.flush()
        try:
            self.log_file.flush()
        except (ValueError, OSError):
            pass

    def fileno(self):
        return self.console.fileno()

    @property
    def encoding(self):
        return getattr(self.console, "encoding", "utf-8")

    def isatty(self):
        return self.console.isatty()


